// rule updates both in the same change. Words as the app's Greek uses them: "πρόταση" for an offer,
// "διανομέας" for a rider, "κατάστημα" for a restaurant, "συντονισμός" for dispatch, "Αποδοχές" for the
// Earnings screen, "επανεξέταση" for a review, the polite plural throughout.

// "περίπου 6 μήνες" for 182 days; whole months, at least one (the Greek of `aboutMonths`).
function aboutMonthsEl(days: number): string {
  const months = Math.max(1, Math.round(days / 30.44))
  return `περίπου ${months} ${months === 1 ? 'μήνας' : 'μήνες'}`
}

